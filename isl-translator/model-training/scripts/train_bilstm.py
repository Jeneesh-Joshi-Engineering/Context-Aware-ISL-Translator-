    parser = argparse.ArgumentParser(description="Train a BiLSTM on a versioned ISL dataset.")
    parser.add_argument("--data-dir", default=None, help="Processed dataset version directory.")
    parser.add_argument("--output-dir", default=None, help="Directory for trained model artifacts.")
    args = parser.parse_args()
    script_dir = Path(__file__).parent
    data_dir = Path(args.data_dir) if args.data_dir else script_dir.parent / "dataset" / "processed" / "v1"
    output_dir = Path(args.output_dir) if args.output_dir else script_dir.parent / "saved_model" / f"transit_{data_dir.name}"
    
    if not data_dir.exists():
        print(f"❌ Data directory not found: {data_dir}")
        print("   Run build_dataset.py first!")
        exit(1)
    
    model, history, accuracy, loss = train_model(data_dir, output_dir)
